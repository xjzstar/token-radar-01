// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and adds every pre-token protocol below the floor that the house's
// own watchlist rule would keep: no token recorded, not a wrapped, staked or
// bridged product, not a versioned pool, not an exchange product. Live-token
// protocols are kept apart and shown with the market's own values.
//
// Implied value is a comparables model, computed from the snapshot alone:
//
//   category multiple = median (market cap / TVL) of the live-token
//     protocols in the same category, when at least 3 such protocols exist;
//     otherwise the global median across all live-token protocols.
//     The multiple is clamped to [0.05, 1.50] so one outlier cannot set it.
//   base       = tvl_usd x category multiple
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.6
//   maturity   = 0.75 + min(age_days, 1095) / 1095 x 0.25
//                (age unknown: 365 days)
//   chains     = 1 + min(chains - 1, 4) x 0.02
//   implied    = max(1, round(base x growthMult x maturity x chains))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the category multiple is recomputed from the snapshot on every run, so
// the model follows the data rather than a hand-written list.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_step: number;
  chain_max_steps: number;
  multiple_min: number;
  multiple_max: number;
  min_comparables: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.75,
  maturity_range: 0.25,
  maturity_days: 1095,
  unknown_age_days: 365,
  chain_step: 0.02,
  chain_max_steps: 4,
  multiple_min: 0.05,
  multiple_max: 1.5,
  min_comparables: 3,
};

